#!/usr/bin/env python3
"""Produce a conservative linear MCS-48/8039 listing from a ROM image.

The output is a mechanical disassembly, not a control-flow or data-flow
recovery.  It preserves bytes that do not decode as documented MCS-48
instructions as DB directives and collapses long erased (FF) regions into DB
lines.  This makes the listing auditable against the input image.
"""
from __future__ import annotations

import argparse
from pathlib import Path


ONE_BYTE = {
    0x00: "NOP", 0x02: "OUTL BUS,A", 0x05: "EN I", 0x07: "DEC A",
    0x08: "INS A,BUS", 0x09: "IN A,P1", 0x0A: "IN A,P2",
    0x0C: "MOVD A,P4", 0x0D: "MOVD A,P5", 0x0E: "MOVD A,P6",
    0x0F: "MOVD A,P7", 0x10: "INC @R0", 0x11: "INC @R1",
    0x15: "DIS I", 0x17: "INC A", 0x20: "XCH A,@R0",
    0x21: "XCH A,@R1", 0x25: "EN TCNTI", 0x27: "CLR A",
    0x30: "XCHD A,@R0", 0x31: "XCHD A,@R1", 0x35: "DIS TCNTI",
    0x37: "CPL A", 0x39: "OUTL P1,A", 0x3A: "OUTL P2,A",
    0x3C: "MOVD P4,A", 0x3D: "MOVD P5,A", 0x3E: "MOVD P6,A",
    0x3F: "MOVD P7,A", 0x40: "ORL A,@R0", 0x41: "ORL A,@R1",
    0x42: "MOV A,T", 0x45: "STRT CNT", 0x47: "SWAP A",
    0x50: "ANL A,@R0", 0x51: "ANL A,@R1", 0x55: "STRT T",
    0x57: "DA A", 0x60: "ADD A,@R0", 0x61: "ADD A,@R1",
    0x62: "MOV T,A", 0x65: "STOP TCNT", 0x67: "RRC A",
    0x70: "ADDC A,@R0", 0x71: "ADDC A,@R1", 0x75: "ENT0 CLK",
    0x77: "RR A", 0x80: "MOVX A,@R0", 0x81: "MOVX A,@R1",
    0x83: "RET", 0x85: "CLR F0", 0x8C: "ORLD P4,A",
    0x8D: "ORLD P5,A", 0x8E: "ORLD P6,A", 0x8F: "ORLD P7,A",
    0x90: "MOVX @R0,A", 0x91: "MOVX @R1,A", 0x93: "RETR",
    0x95: "CPL F0", 0x97: "CLR C", 0x9C: "ANLD P4,A",
    0x9D: "ANLD P5,A", 0x9E: "ANLD P6,A", 0x9F: "ANLD P7,A",
    0xA0: "MOV @R0,A", 0xA1: "MOV @R1,A", 0xA3: "MOVP A,@A",
    0xA5: "CLR F1", 0xA7: "CPL C", 0xB3: "JMPP @A",
    0xB5: "CPL F1", 0xC5: "SEL RB0", 0xC7: "MOV A,PSW",
    0xD5: "SEL RB1", 0xD7: "MOV PSW,A", 0xE3: "MOVP3 A,@A",
    0xE5: "SEL MB0", 0xE7: "RL A", 0xF5: "SEL MB1", 0xF7: "RLC A",
}

for base, mnemonic in ((0x18, "INC R"), (0x28, "XCH A,R"),
                       (0x48, "ORL A,R"), (0x58, "ANL A,R"),
                       (0x68, "ADD A,R"), (0x78, "ADDC A,R"),
                       (0xA8, "MOV R",), (0xC8, "DEC R"),
                       (0xD8, "XRL A,R"), (0xF8, "MOV A,R")):
    for register in range(8):
        ONE_BYTE[base + register] = f"{mnemonic}{register}" if mnemonic != "MOV R" else f"MOV R{register},A"

TWO_BYTE = {
    0x03: "ADD A,#", 0x13: "ADDC A,#", 0x23: "MOV A,#",
    0x43: "ORL A,#", 0x53: "ANL A,#", 0xD3: "XRL A,#",
    0x88: "ORL BUS,#", 0x89: "ORL P1,#", 0x8A: "ORL P2,#",
    0x98: "ANL BUS,#", 0x99: "ANL P1,#", 0x9A: "ANL P2,#",
    0xB0: "MOV @R0,#", 0xB1: "MOV @R1,#",
}
for base, mnemonic in ((0xB8, "MOV R"),):
    for register in range(8):
        TWO_BYTE[base + register] = f"{mnemonic}{register},#"

PAGE_JUMPS = {0x04 + (page << 5): "JMP" for page in range(8)}
PAGE_CALLS = {0x14 + (page << 5): "CALL" for page in range(8)}
BIT_BRANCHES = {0x12 + (bit << 5): f"JB{bit}" for bit in range(8)}
BRANCHES = {
    0x16: "JTF", 0x26: "JNT0", 0x36: "JT0", 0x46: "JNT1", 0x56: "JT1",
    0x76: "JF1", 0x86: "JNI", 0x96: "JNZ", 0xC6: "JZ", 0xE6: "JNC", 0xF6: "JC",
}
DJNZ = {0xE8 + register: f"DJNZ R{register}" for register in range(8)}


def db_lines(data: bytes, address: int) -> list[str]:
    lines = []
    for offset in range(0, len(data), 16):
        chunk = data[offset:offset + 16]
        bytes_text = " ".join(f"{byte:02X}" for byte in chunk)
        directive = ", ".join(f"{byte:02X}h" for byte in chunk)
        lines.append(f"        DB {directive:<77} ; {address + offset:04X}: {bytes_text}")
    return lines


def decode(data: bytes, address: int) -> tuple[int, str]:
    opcode = data[address]
    if opcode in ONE_BYTE:
        return 1, ONE_BYTE[opcode]
    if address + 1 >= len(data):
        return 1, f"DB {opcode:02X}h"
    operand = data[address + 1]
    if opcode in PAGE_JUMPS | PAGE_CALLS:
        target = ((opcode & 0xE0) << 3) | operand
        return 2, f"{(PAGE_JUMPS | PAGE_CALLS)[opcode]} {target:03X}h"
    if opcode in BIT_BRANCHES | BRANCHES:
        target = (address & 0xF00) | operand
        return 2, f"{(BIT_BRANCHES | BRANCHES)[opcode]} {target:03X}h"
    if opcode in DJNZ:
        target = (address & 0xF00) | operand
        return 2, f"{DJNZ[opcode]} {target:03X}h"
    if opcode in TWO_BYTE:
        return 2, f"{TWO_BYTE[opcode]}{operand:02X}h"
    return 1, f"DB {opcode:02X}h"


def disassemble(data: bytes, used_end: int) -> str:
    lines = [
        "; Mechanical MCS-48 / INS8039 linear disassembly.",
        "; Input: Petster Deluxe 27C32 ROM, base address 000h.",
        "; Generated by scripts/disassemble-mcs48.py; preserve the BIN as the source of truth.",
        "; Branch targets are calculated from MCS-48 page rules.  Data/code classification",
        "; and labels require hardware observation or control-flow analysis and are intentionally absent.",
        "", "ORG 000h", "",
    ]
    address = 0
    while address <= used_end:
        if data[address] == 0xFF:
            end = address
            while end <= used_end and data[end] == 0xFF:
                end += 1
            if end - address >= 8:
                lines.extend(db_lines(data[address:end], address))
                address = end
                continue
        size, instruction = decode(data, address)
        raw = data[address:address + size]
        bytes_text = " ".join(f"{byte:02X}" for byte in raw)
        lines.append(f"        {instruction:<47} ; {address:04X}: {bytes_text}")
        address += size
    if used_end + 1 < len(data):
        lines += ["", f"ORG {used_end + 1:03X}h", "; Erased EPROM padding through 0FFFh:"]
        lines.extend(db_lines(data[used_end + 1:], used_end + 1))
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--used-end", type=lambda value: int(value, 0), default=0x79F)
    args = parser.parse_args()
    data = args.input.read_bytes()
    if len(data) != 0x1000:
        raise SystemExit(f"expected a 4096-byte ROM image, got {len(data)} bytes")
    if not 0 <= args.used_end < len(data):
        raise SystemExit("--used-end is outside the ROM image")
    args.output.write_text(disassemble(data, args.used_end), encoding="ascii")


if __name__ == "__main__":
    main()
